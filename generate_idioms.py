def generate_balanced_idioms(target_count=2000):
    print("正在调整难度配比：80% 简单 + 20% 进阶...")
    
    easy_pool = [w for w in EASY_IDIOMS if len(w) == 4]
    med_pool = [w for w in MEDIUM_IDIOMS if len(w) == 4]
    
    # 按照 4:1 的比例填充
    easy_items = []
    med_items = []

    while len(easy_items) < int(target_count * 0.8):
        for w in easy_pool:
            easy_items.append({"word": w, "length": 4, "difficulty": "easy"})
            if len(easy_items) >= int(target_count * 0.8):
                break

    while len(med_items) < int(target_count * 0.2):
        for w in med_pool:
            med_items.append({"word": w, "length": 4, "difficulty": "medium"})
            if len(med_items) >= int(target_count * 0.2):
                break

    random.shuffle(easy_items)
    random.shuffle(med_items)

    # 4 易 1 难 穿插
    final_list = []
    e_i, m_i = 0, 0
    while len(final_list) < target_count:
        for _ in range(4):
            if e_i < len(easy_items):
                final_list.append(easy_items[e_i])
                e_i += 1
        if m_i < len(med_items):
            final_list.append(med_items[m_i])
            m_i += 1

    final_result = final_list[:target_count]

    with open("idioms.json", "w", encoding="utf-8") as f:
        json.dump(final_result, f, ensure_ascii=False, indent=2)

    print(f"✅ 成功写入 {len(final_result)} 条数据，完成“稍微提升一点点难度”的微调！")

if __name__ == "__main__":
    generate_balanced_idioms(2000)
